export const getBestsellers = () => products.filter((p) => p.is_bestseller);
export const getNewArrivals = () => products.filter((p) => p.is_new_arrival);
export const getProductsByCategory = (slug: string) =>
  products.filter(
    (p) =>
      p.category_name.toLowerCase().replace(/\s+/g, '-') === slug ||
      p.slug.includes(slug) ||
      p.category_id === slug
  );
export const getProductById = (id: string) => products.find((p) => p.id === id);
export const getProductBySlug = (slug: string) => products.find((p) => p.slug === slug);
export const searchProducts = (query: string) =>
  products.filter(
    (p) =>
      p.name.toLowerCase().includes(query.toLowerCase()) ||
      p.material.toLowerCase().includes(query.toLowerCase()) ||
      p.category_name.toLowerCase().includes(query.toLowerCase()) ||
      p.color.toLowerCase().includes(query.toLowerCase()) ||
      p.description.toLowerCase().includes(query.toLowerCase())
  );
