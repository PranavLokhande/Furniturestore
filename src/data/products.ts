// ─── HELPER FOR SEAMLESS MULTI-ANGLE PRODUCTS ─────────────────
const makeProduct = (overrides: Partial<Product> & { id: string; name: string }): Product => {
  const original_price = overrides.original_price ?? 35000;
  const discount_percentage = overrides.discount_percentage ?? 25;
  const calculatedPrice = overrides.price ?? Math.round(original_price * (1 - discount_percentage / 100));

  return {
    slug: overrides.name.toLowerCase().replace(/\s+/g, '-').replace(/[^a-z0-9-]/g, ''),
    category_id: overrides.category_id ?? 'cat-1',
    category_name: overrides.category_name ?? 'Living Room',
    description:
      overrides.description ??
      'Masterfully constructed from 100% seasoned solid hardwood with mortise-and-tenon joinery. High-temperature vacuum kilning ensures timber moisture remains below 8% for permanent warp & termite immunity.',
    original_price,
    discount_percentage,
    price: calculatedPrice,
    rating: overrides.rating ?? 4.8,
    review_count: overrides.review_count ?? 156,
    material: overrides.material ?? 'Solid Sheesham Wood',
    color: overrides.color ?? 'Walnut Brown',
    dimensions: overrides.dimensions ?? { length: 180, width: 85, height: 80, unit: 'cm' },
    images: overrides.images ?? [],
    variants: overrides.variants ?? [],
    tags: overrides.tags ?? ['solid-wood', 'handcrafted'],
    is_bestseller: overrides.is_bestseller ?? false,
    is_new_arrival: overrides.is_new_arrival ?? false,
    is_published: true,
    stock_quantity: overrides.stock_quantity ?? 18,
    warranty_months: 120, // 10 years
    sku: overrides.sku ?? `WC-${overrides.id.toUpperCase()}`,
    created_at: new Date().toISOString(),
    ...overrides,
  };
};

